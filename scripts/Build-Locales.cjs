// Deterministic extension catalogs. No network, packages or executable translations.
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
function output(file, data) {
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file,'utf8') !== data) throw Error(`Stale generated locale: ${file}`);
  } else {
    fs.mkdirSync(path.dirname(file), {recursive:true});
    fs.writeFileSync(file,data);
  }
}
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'locales/extension.json'), 'utf8'));
const registry = JSON.parse(fs.readFileSync(path.join(root, 'locales/languages.json'), 'utf8'));
const languages = registry.map(l => l.code);
const additional = JSON.parse(fs.readFileSync(path.join(root, 'locales/additional.json'), 'utf8'));
const id = key => 'm_' + createHash('sha256').update(key).digest('hex').slice(0, 16);
const runtime = {};
const messages = Object.fromEntries(languages.map(l => [l, {}]));
for (const [key, translations] of Object.entries(catalog).sort(([a],[b])=>a.localeCompare(b, 'en'))) {
  if (translations.length !== 3 || translations.some(t=>typeof t !== 'string' || !t.trim())) throw Error(`Invalid translation: ${key}`);
  const slots = text => [...text.matchAll(/\{\d+\}/g)].map(m=>m[0]).sort().join(',');
  runtime[key] = {};
  for (const [i, language] of languages.entries()) {
    const text = i === 0 ? key : i < 4 ? translations[i-1] : additional[key]?.[i-4] ?? key;
    if (typeof text !== 'string' || !text.trim()) throw Error(`Empty translation in ${language}: ${key}`);
    if (slots(key) !== slots(text)) throw Error(`Placeholder mismatch in ${language}: ${key}`);
    runtime[key][language] = text;
    messages[language][id(key)] = {message:text};
  }
}
for(const {code:language,extensionAliases=[]} of registry) {
  messages[language].extensionName = {message:({en:'Download Engine Integration','zh-CN':'Download Engine 浏览器集成','zh-TW':'Download Engine 瀏覽器整合',ms:'Integrasi Download Engine',ja:'Download Engine 連携',ko:'Download Engine 연동',vi:'Tích hợp Download Engine',th:'ส่วนขยาย Download Engine',pl:'Integracja Download Engine',ru:'Интеграция Download Engine',uk:'Інтеграція Download Engine',ar:'تكامل Download Engine',de:'Download-Engine-Integration',fr:'Intégration Download Engine',sv:'Download Engine-integrering',no:'Download Engine-integrasjon','de-CH':'Download-Engine-Integration',it:'Integrazione Download Engine',rm:'Integraziun Download Engine'})[language]};
  messages[language].extensionDescription = {message:runtime['Capture file downloads and detect videos for the Download Engine desktop app.'][language]};
  for (const code of [language,...extensionAliases]) {
    const dir=path.join(root,'extension/_locales',code.replace('-','_'));
    output(path.join(dir,'messages.json'),JSON.stringify(messages[language],null,2)+'\n');
  }
}
output(path.join(root,'extension/i18n-catalog.js'),'/* Generated by scripts/Build-Locales.cjs. Edit locales/extension.json and locales/additional.json. */\n' +
  'globalThis.IDMLanguageCatalog = '+JSON.stringify(runtime)+';\n');
console.log(`${Object.keys(catalog).length} messages × ${languages.length} extension languages`);
