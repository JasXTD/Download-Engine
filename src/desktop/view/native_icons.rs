//! Small outline icons for systems without Microsoft's private-use icon font.
use eframe::egui::{Color32, Painter, Pos2, Rect, Shape, Stroke, StrokeKind, vec2};

pub(super) fn paint(painter: &Painter, at: Pos2, glyph: &str, size: f32, color: Color32) -> bool {
    let point = |x: f32, y: f32| at + vec2(x - 10.0, y - 10.0) * (size / 20.0);
    let stroke = Stroke::new((size / 14.0).clamp(1.0, 2.0), color);
    let line = |points: &[(f32, f32)]| {
        painter.add(Shape::line(
            points.iter().map(|&(x, y)| point(x, y)).collect(),
            stroke,
        ));
    };
    let outline = |points: &[(f32, f32)]| {
        painter.add(Shape::closed_line(
            points.iter().map(|&(x, y)| point(x, y)).collect(),
            stroke,
        ));
    };
    let rect = |x1: f32, y1: f32, x2: f32, y2: f32| {
        painter.rect_stroke(
            Rect::from_min_max(point(x1, y1), point(x2, y2)),
            1,
            stroke,
            StrokeKind::Middle,
        );
    };
    match glyph {
        "\u{e712}" => {
            for x in [4.0, 10.0, 16.0] {
                painter.circle_filled(point(x, 10.0), size / 14.0, color);
            }
        }
        "\u{e714}" => {
            rect(1.0, 4.0, 13.0, 16.0);
            outline(&[(13.0, 8.0), (19.0, 4.0), (19.0, 16.0), (13.0, 12.0)]);
        }
        "\u{e716}" | "\u{e968}" => {
            line(&[(10.0, 6.0), (10.0, 10.0), (4.0, 10.0), (4.0, 14.0)]);
            line(&[(10.0, 10.0), (16.0, 10.0), (16.0, 14.0)]);
            rect(7.0, 1.0, 13.0, 6.0);
            rect(1.0, 14.0, 7.0, 19.0);
            rect(13.0, 14.0, 19.0, 19.0);
        }
        "\u{e71b}" => {
            outline(&[(2.0, 12.0), (8.0, 6.0), (12.0, 10.0), (6.0, 16.0)]);
            outline(&[(8.0, 10.0), (14.0, 4.0), (18.0, 8.0), (12.0, 14.0)]);
        }
        "\u{e72e}" => {
            rect(3.0, 9.0, 17.0, 19.0);
            line(&[
                (6.0, 9.0),
                (6.0, 5.0),
                (8.0, 2.0),
                (12.0, 2.0),
                (14.0, 5.0),
                (14.0, 9.0),
            ]);
            line(&[(10.0, 12.0), (10.0, 16.0)]);
        }
        "\u{e790}" => {
            outline(&[
                (10.0, 1.0),
                (16.0, 3.0),
                (19.0, 8.0),
                (18.0, 13.0),
                (14.0, 15.0),
                (11.0, 13.0),
                (8.0, 14.0),
                (8.0, 18.0),
                (5.0, 18.0),
                (1.0, 13.0),
                (1.0, 7.0),
                (5.0, 2.0),
            ]);
            for (x, y) in [(5.0, 7.0), (9.0, 5.0), (14.0, 6.0), (15.0, 10.0)] {
                painter.circle_filled(point(x, y), size / 17.0, color);
            }
        }
        "\u{e839}" => {
            rect(1.0, 2.0, 19.0, 14.0);
            line(&[(10.0, 14.0), (10.0, 19.0)]);
            line(&[(5.0, 19.0), (15.0, 19.0)]);
        }
        "\u{e83d}" | "\u{ea18}" => {
            outline(&[
                (10.0, 1.0),
                (18.0, 4.0),
                (17.0, 12.0),
                (14.0, 16.0),
                (10.0, 19.0),
                (6.0, 16.0),
                (3.0, 12.0),
                (2.0, 4.0),
            ]);
            line(&[(6.0, 10.0), (9.0, 13.0), (14.0, 7.0)]);
        }
        "\u{e8a0}" => {
            rect(1.0, 3.0, 19.0, 17.0);
            line(&[(12.0, 3.0), (12.0, 17.0)]);
            line(&[(4.0, 7.0), (9.0, 7.0)]);
            line(&[(4.0, 11.0), (9.0, 11.0)]);
        }
        "\u{e8a5}" => {
            outline(&[
                (3.0, 1.0),
                (12.0, 1.0),
                (17.0, 6.0),
                (17.0, 19.0),
                (3.0, 19.0),
            ]);
            line(&[(12.0, 1.0), (12.0, 6.0), (17.0, 6.0)]);
            for y in [10.0, 14.0] {
                line(&[(6.0, y), (14.0, y)]);
            }
        }
        "\u{e8c8}" => {
            rect(6.0, 6.0, 18.0, 19.0);
            line(&[
                (3.0, 14.0),
                (1.0, 14.0),
                (1.0, 1.0),
                (13.0, 1.0),
                (13.0, 3.0),
            ]);
        }
        "\u{ea86}" => {
            outline(&[
                (2.0, 2.0),
                (8.0, 2.0),
                (8.0, 6.0),
                (12.0, 6.0),
                (12.0, 2.0),
                (18.0, 2.0),
                (18.0, 8.0),
                (14.0, 8.0),
                (14.0, 12.0),
                (18.0, 12.0),
                (18.0, 18.0),
                (2.0, 18.0),
            ]);
        }
        _ => return false,
    }
    true
}
